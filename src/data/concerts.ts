/** Shows on or after this date are still ahead of the box office. */
export const BOX_OFFICE_OPEN = "2026-11-01";

const CITY_POSTER: Record<string, string> = {
  Kaohsiung: "/concerts/cities/kaohsiung.jpg",
  Bangkok: "/concerts/cities/bangkok.jpg",
  "Kuala Lumpur": "/concerts/cities/kuala-lumpur.jpg",
  Singapore: "/concerts/cities/singapore.jpg",
  Jakarta: "/concerts/cities/jakarta.jpg",
  Melbourne: "/concerts/cities/melbourne.jpg",
  Sydney: "/concerts/cities/sydney.jpg",
  "Hong Kong": "/concerts/cities/hong-kong.jpg",
  Bulacan: "/concerts/cities/bulacan.jpg",
};

export function concertPoster(city: string) {
  return CITY_POSTER[city] ?? "/concerts/arirang-hero.jpg";
}

function localToday() {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

export function resolveConcertStatus(date: string): Concert["status"] {
  const today = localToday();
  if (date < BOX_OFFICE_OPEN || date < today) return "past";
  if (date >= "2027-01-01") return "upcoming";
  return "onsale";
}

export const concerts: Concert[] = concertSchedule.map((c) => ({
  ...c,
  status: resolveConcertStatus(c.date),
  image: concertPoster(c.city),
}));

export function isSellableConcert(concert: Concert) {
  return concert.date >= BOX_OFFICE_OPEN && concert.date >= localToday();
}

export function getSellableConcerts() {
  return concerts.filter(isSellableConcert);
}

export function getUpcomingConcerts(limit = 3) {
  return getSellableConcerts().slice(0, limit);
}

export function getConcertsByRegion(region: Concert["region"] | "all") {
  if (region === "all") return concerts;
  return concerts.filter((c) => c.region === region);
}

export function getConcertById(id: string) {
  return concerts.find((c) => c.id === id);
}
